"""millproject generation + coordinate frame (FR5).

FR5.3: the frame is ALWAYS zero-start=0 with explicit offsets - never
zero-start=1 (the bounding-box origin silently shifts every output when
isolation-width changes). The fixed frame is the KiCad-page transform:
x-offset = -MX, y-offset = MY, the same constants kicad_regions.py uses
(G54 = M - kicad_mm/25.4, X mirrored), optionally plus a per-blank
placement delta from the DRO-read blank corner.

Frames are verified by MEASUREMENT, never by assumption: on a mirrored
back-side board x-offset acts in mirrored X (a positive value moves the
toolpath more negative). The solver runs pcb2gcode, reads actual extents
out of the generated G-code, computes the gain empirically, and verifies
with a final run; drill_frame_stability() proves the frame does not move
when isolation-width changes (drill G-code byte-identical).
"""

import os
import shutil
import subprocess
import tempfile

from .gcodeio import GCodeAnalysis
from .toollib import ToolLibrary, mill_diameter_for

PCB2GCODE = shutil.which("pcb2gcode") or "pcb2gcode"


def build_millproject(job, tool_library=None):
    """Render the millproject text from job parameters. FR3.2: the
    mill-diameters value is recomputed from zwork + the isolation tool's
    geometry every time - they cannot drift apart."""
    p = job.params
    cam = p["cam"]
    tools = p["tools"]
    lib = tool_library or ToolLibrary()
    iso = lib.get(tools["isolation_tool"])
    if iso is None:
        raise ValueError("isolation tool %r not in the tool library"
                         % tools["isolation_tool"])
    mill_dia = mill_diameter_for(iso, cam["zwork"])

    gerber = job.input_path("gerber_back")
    drill = job.input_path("drill")
    if not gerber or not drill:
        raise ValueError("job needs gerber_back and drill inputs first")

    lines = [
        "# GENERATED by pcbmill - do not edit; change job parameters instead.",
        "# mill-diameters is derived from zwork and the isolation tool:",
        "#   %s at zwork=%g -> kerf %.4f" % (iso["label"], cam["zwork"], mill_dia),
        "software=linuxcnc",
        "",
        # back=, never front=, for a B.Cu board - pcb2gcode handles the mirror
        "back=%s" % os.path.relpath(gerber, job.root),
        "drill=%s" % os.path.relpath(drill, job.root),
    ]
    if cam.get("outline_enabled") and job.input_path("edge_cuts"):
        lines.append("outline=%s" % os.path.relpath(job.input_path("edge_cuts"), job.root))
    lines += [
        "",
        "output-dir=out",
        "basename=%s" % job.basename,
        "",
        "mill-diameters=%.4f" % mill_dia,
    ]
    if cam.get("isolation_width"):
        lines += [
            "isolation-width=%.4f" % cam["isolation_width"],
            "milling-overlap=%s" % cam["milling_overlap"],
        ]
    lines += [
        "zwork=%g" % cam["zwork"],
        "mill-feed=%g" % cam["mill_feed"],
        "mill-vertfeed=%g" % cam["mill_vertfeed"],
        "mill-speed=%d" % cam["mill_speed"],
        "",
        "drills-available=%s" % ",".join("%g" % d for d in tools["drills_available"]),
        "zdrill=%g" % cam["zdrill"],
        "drill-feed=%g" % cam["drill_feed"],
        "drill-speed=%d" % cam["drill_speed"],
        "nog81=1",
        "",
        "zsafe=%g" % cam["zsafe"],
        "zchange=%g" % cam["zchange"],
    ]
    if cam.get("outline_enabled"):
        lines += [
            "zcut=%g" % cam["zcut_outline"],
            "cutter-diameter=%g" % cam["outline_tool_diameter"],
            "cut-feed=%g" % cam["outline_feed"],
            "cut-vertfeed=%g" % cam["mill_vertfeed"],
            "cut-speed=%d" % cam["mill_speed"],
            "cut-infeed=%g" % abs(cam["zcut_outline"]),
        ]
    lines += [""]
    # NEVER emit al-* options: the autoleveller emits Mach3 G31.
    # FR5.3: ALWAYS zero-start=0 with explicit offsets - never zero-start=1.
    # zero-start derives the origin from the job's bounding box, so anything
    # that grows the outermost pass (isolation-width!) silently shifts EVERY
    # output including the drill file.
    if cam.get("zero_start"):
        raise ValueError(
            "zero-start is forbidden (FR5.3): it silently shifts every output "
            "when isolation-width changes. Set the fixed frame instead "
            "(x-offset = -MX, y-offset = MY, the kicad_regions.py constants).")
    if cam["x_offset"] is None or cam["y_offset"] is None:
        raise ValueError(
            "fixed frame needs x_offset/y_offset - set them from the "
            "KiCad-page transform (x-offset = -MX, y-offset = MY) or run "
            "the measurement solver")
    lines += [
        "# fixed frame - do NOT reintroduce zero-start; widening isolation",
        "# moves the bounding box and silently shifts every output",
        "zero-start=0",
        "x-offset=%.4f" % cam["x_offset"],
        "y-offset=%.4f" % cam["y_offset"],
    ]
    return "\n".join(lines) + "\n"


def run_pcb2gcode(job, millproject_path, cwd=None, extra_args=()):
    cmd = [PCB2GCODE, "--config", millproject_path, *extra_args]
    proc = subprocess.run(cmd, cwd=cwd or job.root,
                          capture_output=True, text=True, timeout=600)
    return proc


# ---------------------------------------------------------------- frame

def set_frame_from_page_transform(job, mx, my, dx=0.0, dy=0.0):
    """FR5.3: x-offset = -(MX+dx), y-offset = MY+dy.

    (MX, MY) are the kicad_regions.py constants (board 1: 4.3372, 3.2478);
    (dx, dy) is an optional per-blank placement delta in G54 inches from
    the DRO-read blank corner."""
    job.params["cam"]["x_offset"] = round(-(mx + dx), 4)
    job.params["cam"]["y_offset"] = round(my + dy, 4)
    job.params["cam"]["zero_start"] = 0
    job.save()
    return {"x_offset": job.params["cam"]["x_offset"],
            "y_offset": job.params["cam"]["y_offset"]}


def drill_frame_stability(job):
    """FR5.3 verification: regenerate with a different isolation-width and
    confirm the drill G-code is byte-identical. Returns (ok, detail)."""
    iso = job.params["cam"].get("isolation_width")
    other = 0.030 if not iso else round(iso + 0.010, 4)
    with tempfile.TemporaryDirectory(prefix="pcbmill-frame-") as td:
        outs = []
        for sub, width in (("a", iso), ("b", other)):
            saved = job.params["cam"].get("isolation_width")
            try:
                job.params["cam"]["isolation_width"] = width
                text = build_millproject(job)
            finally:
                job.params["cam"]["isolation_width"] = saved
            work = os.path.join(td, sub)
            os.makedirs(os.path.join(work, "out"), exist_ok=True)
            for key in ("gerber_back", "drill", "edge_cuts"):
                src = job.input_path(key)
                if src:
                    rel = os.path.relpath(src, job.root)
                    dst = os.path.join(work, rel)
                    os.makedirs(os.path.dirname(dst), exist_ok=True)
                    shutil.copyfile(src, dst)
            with open(os.path.join(work, "millproject"), "w") as fh:
                fh.write(text)
            proc = subprocess.run([PCB2GCODE, "--config", "millproject"],
                                  cwd=work, capture_output=True, text=True,
                                  timeout=600)
            if proc.returncode != 0:
                return False, "pcb2gcode failed: %s" % proc.stderr[-300:]
            outs.append(os.path.join(work, "out",
                                     "%s_drill.ngc" % job.basename))
        a = open(outs[0], "rb").read()
        b = open(outs[1], "rb").read()
        if a == b:
            return True, ("drill G-code byte-identical at isolation-width "
                          "%s vs %s - frame is fixed" % (iso, other))
        return False, ("DRILL G-CODE MOVED between isolation-width %s and %s "
                       "- the frame is NOT fixed (zero-start leak?)"
                       % (iso, other))


# ---------------------------------------------------------------- solver

def _measure_extents(job, x_offset, y_offset, workdir):
    """Run pcb2gcode with the given offsets in a scratch dir; return the
    back-file extents read from the G-CODE (not from console output)."""
    os.makedirs(workdir, exist_ok=True)
    saved = dict(job.params["cam"])
    try:
        job.params["cam"]["x_offset"] = x_offset
        job.params["cam"]["y_offset"] = y_offset
        job.params["cam"]["zero_start"] = 0
        text = build_millproject(job)
    finally:
        job.params["cam"].update(saved)

    mp = os.path.join(workdir, "millproject")
    with open(mp, "w") as fh:
        fh.write(text)
    os.makedirs(os.path.join(workdir, "out"), exist_ok=True)
    # inputs are referenced relative to job root in the config; copy them in
    for key in ("gerber_back", "drill", "edge_cuts"):
        src = job.input_path(key)
        if src:
            rel = os.path.relpath(src, job.root)
            dst = os.path.join(workdir, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copyfile(src, dst)
    proc = subprocess.run([PCB2GCODE, "--config", "millproject"],
                          cwd=workdir, capture_output=True, text=True,
                          timeout=600)
    if proc.returncode != 0:
        raise RuntimeError("pcb2gcode failed in solver:\n" + proc.stderr[-2000:])
    back = os.path.join(workdir, "out", "%s_back.ngc" % job.basename)
    ana = GCodeAnalysis(back)
    ext = ana.xy_extents()
    if ext is None:
        raise RuntimeError("no cutting moves found in solver output")
    return ext


def solve_offsets(job, log=print):
    """Center the copper on the blank by measurement (FR5.3).

    Runs pcb2gcode at two trial offsets per axis to measure the gain
    (which is -1 in mirrored X), solves, regenerates, and VERIFIES the
    result by re-reading the extents.
    """
    blank = job.params["blank"]
    target_cx = blank["x0"] + blank["width"] / 2.0
    target_cy = blank["y0"] + blank["height"] / 2.0

    with tempfile.TemporaryDirectory(prefix="pcbmill-solver-") as td:
        e0 = _measure_extents(job, 0.0, 0.0, os.path.join(td, "a"))
        log("solver: offsets (0,0) -> extents X %.4f..%.4f Y %.4f..%.4f"
            % (e0[0], e0[2], e0[1], e0[3]))
        step = 0.1
        e1 = _measure_extents(job, step, step, os.path.join(td, "b"))
        c0 = ((e0[0] + e0[2]) / 2, (e0[1] + e0[3]) / 2)
        c1 = ((e1[0] + e1[2]) / 2, (e1[1] + e1[3]) / 2)
        gx = (c1[0] - c0[0]) / step
        gy = (c1[1] - c0[1]) / step
        if abs(gx) < 0.5 or abs(gy) < 0.5:
            raise RuntimeError("offset gain measured near zero (gx=%.2f gy=%.2f)"
                               " - pcb2gcode not honoring offsets?" % (gx, gy))
        log("solver: measured gain X %+.2f (mirrored X shows -1), Y %+.2f"
            % (gx, gy))
        x_off = (target_cx - c0[0]) / gx
        y_off = (target_cy - c0[1]) / gy

        e2 = _measure_extents(job, x_off, y_off, os.path.join(td, "c"))
        c2 = ((e2[0] + e2[2]) / 2, (e2[1] + e2[3]) / 2)
        err = math_hypot(c2[0] - target_cx, c2[1] - target_cy)
        log("solver: verify at (%.4f, %.4f) -> centre (%.4f, %.4f), "
            "target (%.4f, %.4f), error %.4f in"
            % (x_off, y_off, c2[0], c2[1], target_cx, target_cy, err))
        if err > 0.005:
            raise RuntimeError(
                "solver verification failed: centre error %.4f in" % err)
        copper_w = e2[2] - e2[0]
        copper_h = e2[3] - e2[1]
        if copper_w > blank["width"] or copper_h > blank["height"]:
            raise RuntimeError(
                "copper (%.3f x %.3f) does not fit the blank (%.3f x %.3f)"
                % (copper_w, copper_h, blank["width"], blank["height"]))

    job.params["cam"]["x_offset"] = round(x_off, 4)
    job.params["cam"]["y_offset"] = round(y_off, 4)
    job.params["cam"]["zero_start"] = 0
    job.save()
    return {"x_offset": round(x_off, 4), "y_offset": round(y_off, 4),
            "extents": e2, "centre_error_in": round(err, 5)}


def math_hypot(a, b):
    return (a * a + b * b) ** 0.5
